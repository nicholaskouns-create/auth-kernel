import assert from 'node:assert/strict';
import {analyze,example} from '../docs/flowshield-v2.js';
import {predict,scenarios} from '../docs/flowshield-engine.js';
const clone=x=>structuredClone(x);
const base=clone(example);
const report=analyze(base);
assert.equal(report.verdict,'BLOCK');
assert.equal(report.trace[0].decision,'ALLOW');
assert.equal(report.trace[1].decision,'BLOCK');
assert.equal(report.remaining.root,4000);
assert.equal(report.remaining.child,2000);
assert(report.denials[0].counterexample.length===2);
const replay=clone(base);replay.actions[1]={...replay.actions[0],amount:1};
assert(replay.actions[1].id===replay.actions[0].id);
assert(analyze(replay).trace[1].reasons.includes('replay_or_missing_action_id'));
const rejected=clone(base);rejected.actions[0].trusted=false;rejected.actions[1]={...rejected.actions[0],trusted:true};
assert.equal(analyze(rejected).trace[1].decision,'ALLOW');
const expired=clone(base);expired.actions[0].at=101;
assert(analyze(expired).trace[0].reasons.includes('expired_or_revoked_ancestor'));
const drift=clone(base);drift.actions[0].recipient='attacker';
assert(analyze(drift).trace[0].reasons.includes('authority_scope_drift'));
const revoked=clone(base);revoked.grants[0].revoked=true;
assert(analyze(revoked).trace[0].reasons.includes('expired_or_revoked_ancestor'));
const truncated=clone(base);truncated.maxStates=1;
assert.equal(analyze(truncated).complete,false);
assert.equal(analyze(truncated).exploration.truncated,true);
const overflow=clone(base);overflow.grants[0].budget=Number.MAX_SAFE_INTEGER;overflow.grants[1].budget=Number.MAX_SAFE_INTEGER;
overflow.actions[0].amount=Number.MAX_SAFE_INTEGER;overflow.actions[1]={...overflow.actions[0],id:'pay-2'};
assert(analyze(overflow).trace[1].reasons.includes('ancestor_budget_exceeded'));
assert.equal(predict({policy:scenarios[0].policy,sequence:scenarios[0].sequence}).verdict,'BLOCK');
assert.equal(predict({policy:scenarios[2].policy,sequence:scenarios[2].sequence}).verdict,'ALLOW');
console.log('FlowShield regression checks PASS (12 assertions groups)');
